import { useCallback, useLayoutEffect, useRef, useState } from "react";
import { ArrowDown } from "lucide-react";
import { Button } from "@/components/common/Button";
import { AssistantMessage } from "@/components/chat/AssistantMessage";
import { Composer } from "@/components/chat/Composer";
import { Welcome } from "@/components/chat/Welcome";
import { useMediaQuery } from "@/hooks/useMediaQuery";
import { useChat } from "@/state/ChatContext";
import { useDetailDialog } from "@/state/DetailDialogContext";
import { useResearchData } from "@/state/ResearchDataContext";
import { useServices } from "@/state/ServicesContext";
import { useToast } from "@/state/ToastContext";
import styles from "@/components/chat/Chat.module.css";

const NEAR_BOTTOM_PX = 160;

export function AskAmplifiPage() {
  const chat = useChat();
  const { library } = useResearchData();
  const { openPaper } = useDetailDialog();
  const { config } = useServices();
  const { showToast } = useToast();
  const desktop = useMediaQuery("(min-width: 992px)");
  const scrollRef = useRef<HTMLDivElement>(null);
  const [pinned, setPinned] = useState(true);

  const isMock = config.chatMode === "mock";
  const messages = chat.messages;

  // Follow the answer as it streams, unless the person has scrolled up to read.
  useLayoutEffect(() => {
    const el = scrollRef.current;
    if (el && pinned) el.scrollTop = el.scrollHeight;
  }, [messages, pinned]);

  const onScroll = () => {
    const el = scrollRef.current;
    if (el) setPinned(el.scrollHeight - el.scrollTop - el.clientHeight < NEAR_BOTTOM_PX);
  };

  const send = useCallback(
    (q: string) => {
      setPinned(true);
      chat.send(q);
    },
    [chat],
  );

  const copy = useCallback(
    (text: string) => {
      if (!navigator.clipboard?.writeText) {
        showToast("Copying isn’t available in this browser. Select the text instead.", "error");
        return;
      }
      navigator.clipboard.writeText(text).then(
        () => showToast("Copied to the clipboard."),
        () => showToast("Couldn’t copy. Select the text instead.", "error"),
      );
    },
    [showToast],
  );

  const feedback = useCallback(
    (id: string, v: "up" | "down" | null) => {
      chat.setFeedback(id, v);
      if (v) showToast("Thanks. Your rating is noted for this session.");
    },
    [chat, showToast],
  );

  return (
    <div className={styles.page}>
      <div className={styles.toolbar}>
        <span className={`muted small ${styles.toolbarNote}`}>Answers come from the papers in the knowledge base</span>
        <Button variant="quiet" onClick={chat.newChat} disabled={!messages.length}>
          New chat
        </Button>
      </div>
      <div className={styles.scroll} ref={scrollRef} onScroll={onScroll}>
        <div className={styles.col}>
          {messages.length === 0 ? (
            <Welcome onAsk={send} isMock={isMock} />
          ) : (
            <ol className={styles.thread} aria-label="Conversation" aria-live="polite" aria-busy={chat.isBusy}>
              {messages.map((m, i) => (
                <li key={m.id}>
                  {m.role === "user" ? (
                    <div className={styles.user}>
                      <span className="visually-hidden">You asked: </span>
                      <div className={styles.bubble}>{m.text}</div>
                    </div>
                  ) : (
                    <AssistantMessage
                      message={m}
                      canRegenerate={!chat.isBusy && i > 0}
                      onCite={openPaper}
                      onCopy={copy}
                      onRegenerate={chat.regenerate}
                      onFeedback={feedback}
                    />
                  )}
                </li>
              ))}
            </ol>
          )}
        </div>
      </div>
      <div className={styles.composerWrap}>
        {!pinned && (
          <button
            type="button"
            className={styles.toBottom}
            aria-label="Scroll to the latest message"
            onClick={() => {
              scrollRef.current?.scrollTo({ top: scrollRef.current.scrollHeight, behavior: "smooth" });
              setPinned(true);
            }}
          >
            <ArrowDown aria-hidden="true" />
          </button>
        )}
        <Composer
          busy={chat.isBusy}
          scope={chat.scope}
          papers={library}
          focusRequest={chat.focusRequest}
          autoFocus={desktop}
          onScopeChange={chat.setScope}
          onSend={send}
          onStop={chat.stop}
        />
        <p className={styles.disclaimer}>
          {isMock
            ? "Demo mode: answers are pre-written examples, not generated by Amplifi."
            : "Amplifi answers from the papers and cites its sources. Check important values against the paper."}
        </p>
      </div>
    </div>
  );
}
